package com.lottery.draw.controller;

import com.lottery.draw.dto.DrawRequest;
import com.lottery.draw.dto.DrawResponse;
import com.lottery.draw.security.AuthenticatedUser;
import com.lottery.draw.service.DrawService;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.Parameter;
import io.swagger.v3.oas.annotations.tags.Tag;
import jakarta.validation.Valid;
import org.springframework.http.HttpStatus;
import org.springframework.security.core.annotation.AuthenticationPrincipal;
import org.springframework.web.bind.annotation.*;

@RestController
@RequestMapping("/api/draws")
@Tag(name = "Draws", description = "Run a draw and read results. Running needs ADMIN, reading any logged-in user")
public class DrawController {

    private final DrawService drawService;

    public DrawController(DrawService drawService) {
        this.drawService = drawService;
    }

    @Operation(summary = "Run the draw for a lottery",
            description = "Allowed only after ticket sales have ended. "
                    + "One draw per lottery. Numbers are generated by the server")
    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    public DrawResponse execute(
            @Parameter(hidden = true) @AuthenticationPrincipal AuthenticatedUser user,
            @Parameter(hidden = true) @RequestHeader("Authorization") String authHeader,
            @Valid @RequestBody DrawRequest req) {
        return drawService.execute(user.userId(), authHeader, req);
    }

    @Operation(summary = "Draw result by lottery id")
    @GetMapping("/lottery/{lotteryId}")
    public DrawResponse byLottery(@PathVariable Long lotteryId) {
        return drawService.getByLottery(lotteryId);
    }

    @Operation(summary = "Draw result by public draw code",
            description = "Use the code such as DRW-XXXXXXXXXXXX, not the numeric id")
    @GetMapping("/{drawId}")
    public DrawResponse byDrawId(@PathVariable String drawId) {
        return drawService.getByDrawId(drawId);
    }
}